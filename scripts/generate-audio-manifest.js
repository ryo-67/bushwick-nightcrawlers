#!/usr/bin/env node
/**
 * scripts/generate-audio-manifest.js
 *
 * Regenerates src/audio/manifest.js from the current contents of
 * assets/sounds/usvs/ and assets/sounds/usvs-cocaine/. Filters to
 * .wav, sorts alphabetically.
 *
 * Run whenever audio files are added or removed:
 *
 *     node scripts/generate-audio-manifest.js
 *
 * The output (src/audio/manifest.js) is committed to the repo so the
 * runtime engine can import it without a build step.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

function listWavs(relativeDir) {
  const full = path.join(ROOT, relativeDir);
  return fs
    .readdirSync(full)
    .filter((f) => f.endsWith('.wav'))
    .sort();
}

const usvs = listWavs('assets/sounds/usvs');
const usvsCocaine = listWavs('assets/sounds/usvs-cocaine');

const out = `// Generated by scripts/generate-audio-manifest.js — do not edit by hand.
// Re-run that script when audio files are added or removed.

export const USVS = ${JSON.stringify(usvs, null, 2)};

export const USVS_COCAINE = ${JSON.stringify(usvsCocaine, null, 2)};
`;

const outPath = path.join(ROOT, 'src/audio/manifest.js');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);

console.log(`Wrote ${path.relative(ROOT, outPath)}`);
console.log(`  usvs: ${usvs.length}`);
console.log(`  usvs-cocaine: ${usvsCocaine.length}`);
